-- Remove money that could only have been generated by the old demo/bonus flows.
-- Genuine task rewards are not touched.
DELETE FROM public.transactions
WHERE label IN ('Referral bonus', 'Welcome invite bonus')
   OR label LIKE 'Daily check-in — day %'
   OR label IN (
     'Verified — Alpha Signals',
     'Verified — Nova Wallet',
     'Verified — TASKORA',
     'Verified — PayLink Africa',
     'Verified — Loop Studio',
     'Verified — Zenith Labs',
     'Verified — Aurum Wear'
   );

-- Never expose exhausted tasks in marketplace queries.
CREATE INDEX IF NOT EXISTS tasks_active_slots_idx
  ON public.tasks(is_active, slots_left);
