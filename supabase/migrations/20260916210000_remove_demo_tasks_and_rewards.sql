-- TASKORA production-data cleanup.
-- The initial schema migration inserted sample/demo marketplace tasks. Remove
-- those records so the Telegram Mini App starts with an empty real marketplace.

DELETE FROM public.submissions
WHERE task_id IN (
  SELECT id FROM public.tasks
  WHERE title IN (
    'Join the Alpha Signals channel',
    'Watch & like the launch video',
    'Follow @taskora and repost the pinned post',
    'Join the merchant community group',
    'Follow the creator account',
    'Join the community server',
    'Follow and save the brand post'
  )
  AND advertiser IN (
    'Alpha Signals',
    'Nova Wallet',
    'TASKORA',
    'PayLink Africa',
    'Loop Studio',
    'Zenith Labs',
    'Aurum Wear'
  )
);

DELETE FROM public.tasks
